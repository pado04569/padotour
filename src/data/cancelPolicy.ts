/**
 * 위약금 계단처럼 보이는 줄인지 판단한다.
 * 표준 규정으로 대체되므로 화면에서 제외하고, 나머지는 상품별 안내로 남긴다.
 */
export function isCancelLadderLine(line: string): boolean {
  return /\d+\s*일\s*전|예약\s*후\s*:|\d+\s*%/.test(line);
}
